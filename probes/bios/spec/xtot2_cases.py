"""docs/bios/TOTEXT.md round 2 (2026-11-17): the XTOT2 supplement, after the first review. XTOT's OLDSCR took 0 / 1 /
$5A, its CRTCNT always 24, its CNSDFG "on" always 1, its colours one set, its entry register copies always the mode
call's, and SCRMOD always agreed with them. ONE case list that GENERATES probes/bios/spec/xtot2.asm's table and DECODES
its run:

    python3 probes/bios/spec/xtot2_cases.py --gen
    python3 -u probes/bios/biosl_run.py probes/bios/spec/xtot2.asm --row nodisk > scratchpad/XTOT2_run1.out

The setup: CNSDFG := 0, LINL40 := 40, LINL32 := 32, the case's colours, then the mode's call (INITXT / INIT32 / INIGRP /
INIMLT); then: SCRMOD := `scr` when it is not $FF (disagreeing with the copies the call set); RG0SAV := `rg0` and
RG1SAV := `rg1` when not $FF; OLDSCR := `old`; LINL40 := 37, LINL32 := 29; LINLEN := 50; CNSDFG := `cns`; CRTCNT :=
`crt`; all of VRAM := $5A; CSRX := 7, CSRY := 5. Then TOTEXT, and one 30-byte record: RG0SAV..RG7SAV, SCRMOD, OLDSCR,
LINLEN, CRTCNT, CSRX, CSRY, CNSDFG, the first 12 cells of row CRTCNT (13 / 24) of SCREEN 0's name table ($0000) or,
when SCRMOD is 1 after, of SCREEN 1's ($1800), sum16 of all 16 KB of VRAM, and the sentinel $C3.
"""
import os
import re
import sys
from types import SimpleNamespace as NS

HERE = os.path.dirname(os.path.abspath(__file__))
ASM = os.path.join(HERE, "xtot2.asm")
REC = 30
SENT = 0xC3
COLOURS = [(15, 4, 4), (3, 10, 9)]


def _cases():
    out = []

    def case(mode=2, old=0, cns=0, crt=24, col=0, scr=0xFF, rg0=0xFF, rg1=0xFF, what=""):
        fg, bg, bd = COLOURS[col]
        out.append(NS(mode=mode, old=old, cns=cns, crt=crt, col=col, scr=scr, rg0=rg0, rg1=rg1, fg=fg, bg=bg, bd=bd,
                      what=what or f"SCREEN {mode} OLDSCR {old:02X}"))
    case(mode=0, scr=2, old=0, what="INITXT's copies, SCRMOD := 2, OLDSCR 0")
    case(mode=2, scr=0, old=1, what="INIGRP's copies, SCRMOD := 0, OLDSCR 1")
    for old in (0, 1):
        case(old=old, cns=1, crt=13, what=f"SCREEN 2 OLDSCR {old} CNSDFG 1 CRTCNT 13")
    for cns in (0xFF, 0x80):
        case(old=0, cns=cns, what=f"SCREEN 2 OLDSCR 0 CNSDFG {cns:02X}")
    for old in (0, 1):
        case(old=old, col=1, what=f"SCREEN 2 OLDSCR {old} colours 3,10,9")
    for old in (0, 1):
        case(old=old, rg0=0x03, rg1=0xE3, what=f"SCREEN 2 OLDSCR {old} RG0SAV 03 RG1SAV E3")
    # the garbage OLDSCR values LAST: a dispatch out of range could crash the machine, and would cost only these
    case(old=0x5A, what="SCREEN 2 OLDSCR 5A (LINLEN preset 50)")
    for old in (2, 3, 0x7F, 0x80, 0x81, 0xFF):
        case(old=old)
    return out


CASES = _cases()


def caplen():
    return 2 + REC * len(CASES)


def table_asm():
    L = ["; ---- GENERATED by xtot2_cases.py --gen: mode, old, cns, crt, fg, bg, bd, scr, rg0, rg1; $FF ends ----",
         "cases:"]
    for c in CASES:
        L.append(f"                db      {c.mode}, ${c.old:02X}, ${c.cns:02X}, {c.crt}, {c.fg}, {c.bg}, {c.bd}, "
                 f"${c.scr:02X}, ${c.rg0:02X}, ${c.rg1:02X}   ; {c.what}")
    L.append("                db      $FE")
    return "\n".join(L) + "\n"


def gen():
    s = open(ASM).read()
    s = s[:s.index("; ---- GENERATED by xtot2_cases.py")] + table_asm()
    s = re.sub(r"; @caplen [0-9A-F]+", f"; @caplen {caplen():04X}", s)
    s = re.sub(r"CAPLEN  equ     \d+", f"CAPLEN  equ     {caplen()}", s)
    open(ASM, "w").write(s)
    print(f"{len(CASES)} cases, capture {caplen()} B")


def decode(block):
    if block[1] != 0xA5 or len(block) < caplen():
        sys.exit("FAIL: the XTOT2 block is not complete")
    out = []
    for i, c in enumerate(CASES):
        b = list(block[2 + REC * i: 2 + REC * (i + 1)])
        if b[REC - 1] != SENT:
            sys.exit(f"FAIL: XTOT2 record {i} has no sentinel")
        out.append(NS(**vars(c), idx=i, rg=b[0:8], scrmod=b[8], oldscr=b[9], linlen=b[10], crtcnt=b[11], csrx=b[12],
                      csry=b[13], cnsdfg=b[14], keyrow=b[15:27], vsum=b[27] | (b[28] << 8)))
    return out


if __name__ == "__main__":
    if "--gen" in sys.argv:
        gen()
    else:
        print(f"{len(CASES)} cases, capture {caplen()} B")
