"""docs/bios/CHPUT.md ROUND 5 (2026-11-17): the fourth review's unseparated pairs and cheap extensions,
as ONE case list that both GENERATES the rung's case table (probes/bios/spec/xchput5.asm) and DECODES
its run -- so the probe's layout and the rules' reading of it cannot drift apart.

    python3 probes/bios/spec/xchput5_cases.py --gen      rewrite xchput5.asm's generated case table
    python3 -u probes/bios/biosl_run.py probes/bios/spec/xchput5.asm --row nodisk > scratchpad/XCH5_run1.out

Every case runs on the NEUTRAL setup of round 4 ("xx" CR 12, VRAM markers -- column 0 'a'+r, 38 'A'+r,
39 '0'+r on every text row -- the cursor cells zeroed, CSRY / CSRX written directly) plus its FLAGS:
  PQR   P Q R at (10, 19..21)
  KEYM  markers in the KEY ROW (row 23): columns 0, 1, 38, 39 = 'K' 'L' 'M' 'N' (the key line on)
  CONT  LINTTB rows 11 and 12 := 0 (continued rows, written directly)
  SET   $FCA9 and $FCAA := 1
and records by KIND:
  CUR   CSRX, CSRY, the cells (10, 18..22)                                        7 B
  XY    ($FCA9), ($FCAA)                                                          2 B
  SEQ   CSRX, CSRY after EVERY byte, then the cells (5, 0..2) and (23, 0..2)       2n + 6 B
  KEY   CSRX, CSRY, the key row's cells at columns 0, 1, 38, 39                   6 B
  EDIT  CSRX, CSRY, LINTTB (24), then columns 0 and 39 of every row 0..23         74 B
  TAB   CSRX, CSRY, LINTTB[22], [23], cells (22,0) (22,39) (23,0) (23,39) (0,0)   9 B
"""
import os
import re
import sys
from types import SimpleNamespace as NS

HERE = os.path.dirname(os.path.abspath(__file__))
ASM = os.path.join(HERE, "xchput5.asm")
PQR, KEYM, CONT, SET = 1, 2, 4, 8
CUR, XY, SEQ, KEY, EDIT, TAB = range(6)
SIZE = {CUR: lambda n: 7, XY: lambda n: 2, SEQ: lambda n: 2 * n + 6, KEY: lambda n: 6,
        EDIT: lambda n: 74, TAB: lambda n: 9}


def _cases():
    out = []

    def add(group, what, seq, kind, key=0, row=10, col=20, flags=PQR):
        out.append(NS(group=group, what=what, seq=list(seq), kind=kind, key=key, row=row, col=col, flags=flags))
    # G1: ESC v then A, every v -- does the escape END, and what does v do?
    for v in range(256):
        add("G1", f"ESC {v} A", (27, v, 65), CUR)
    # G2: v then A, every control code -- is anything left PENDING?
    for v in range(32):
        add("G2", f"{v} A", (v, 65), CUR)
    # G3: ESC y v from BOTH cells set; ESC x v from both clear
    for v in range(256):
        add("G3", f"ESC y {v}", (27, ord("y"), v), XY, flags=PQR | SET)
    for v in range(256):
        add("G3", f"ESC x {v}", (27, ord("x"), v), XY)
    # G4: pending state across the prefix + a byte
    seqs = [("ESC 1 A B", (27, 1, 65, 66)), ("ESC 1 A K", (27, 1, 65, ord("K"))),
            ("ESC x 1 A 5", (27, ord("x"), 1, 65, ord("5"))), ("ESC y 1 A 5", (27, ord("y"), 1, 65, ord("5")))]
    for v in (0, 13, 31, 64, 90, 95, 96, 128, 255):
        seqs.append((f"ESC Y 1 {v} % A", (27, ord("Y"), 1, v, 37, 65)))
    for w, sq in seqs:
        add("G4", w, sq, SEQ, row=10, col=20)
    # G5: the KEY ROW marked, the key line on
    for w, r, c, sq in (("A on the key row", 23, 0, (65,)), ("TAB on the key row", 23, 0, (9,)),
                        ("DEL on the key row", 23, 1, (127,)), ("12", 22, 20, (12,)), ("ESC E", 22, 20, (27, 69)),
                        ("ESC j", 22, 20, (27, ord("j"))), ("ESC J", 22, 20, (27, 74)), ("LF from the last text row", 22, 39, (10,)),
                        ("A at the last text row's end", 22, 39, (65,))):
        add("G5", w, sq, KEY, key=1, row=r, col=c, flags=KEYM)
    # G6: the edits from other places, and on CONTINUED rows
    ops = (("ESC L", (27, 76)), ("ESC M", (27, 77)), ("ESC J", (27, 74)), ("ESC K", (27, 75)), ("ESC l", (27, 108)))
    for (r, c) in ((0, 0), (23, 0), (10, 39)):
        for w, sq in ops:
            add("G6", f"{w} from ({r},{c})", sq, EDIT, row=r, col=c, flags=0)
    for w, sq in ops:
        add("G6", f"{w} from (10,20), rows 11-12 continued", sq, EDIT, row=10, col=20, flags=CONT)
    # G7: TAB from columns 32..38 on the last text row (key line off)
    for c in range(32, 39):
        add("G7", f"TAB from (23,{c})", (9,), TAB, row=23, col=c, flags=0)
    return out


CASES = _cases()


def caplen():
    return 4 + sum(SIZE[c.kind](len(c.seq)) for c in CASES)


def table_asm():
    L = ["; ---- GENERATED by xchput5_cases.py --gen: key, row, col, flags, kind, length, bytes; $FF ends ----",
         "cases:"]
    for c in CASES:
        L.append(f"                db      {c.key}, {c.row}, {c.col}, {c.flags}, {c.kind}, {len(c.seq)}, "
                 + ", ".join(str(b) for b in c.seq) + f"   ; {c.group} {c.what}")
    L.append("                db      $FF")
    return "\n".join(L) + "\n"


def gen():
    s = open(ASM).read()
    a = s.index("; ---- GENERATED by xchput5_cases.py")
    s = s[:a] + table_asm()
    s = re.sub(r"; @caplen [0-9A-F]+", f"; @caplen {caplen():04X}", s)
    s = re.sub(r"CAPLEN  equ     \d+", f"CAPLEN  equ     {caplen()}", s)
    open(ASM, "w").write(s)
    print(f"{len(CASES)} cases, capture {caplen()} B")


def decode(block):
    """the run's block -> one NS per case: the case's fields + rec (the bytes, split by kind)"""
    if block[1] != 0xA5:
        sys.exit("FAIL: the XCHPUT5 block is not complete")
    out, p = [], 4
    for i, c in enumerate(CASES):
        n = SIZE[c.kind](len(c.seq))
        b = list(block[p: p + n])
        p += n
        d = NS(**vars(c), idx=i)
        if c.kind == CUR:
            d.csrx, d.csry, d.cells = b[0], b[1], b[2:7]
        elif c.kind == XY:
            d.csrsw, d.fcaa = b
        elif c.kind == SEQ:
            k = len(c.seq)
            d.cur = [(b[2 * j], b[2 * j + 1]) for j in range(k)]
            d.cells = b[2 * k:]
        elif c.kind == KEY:
            d.csrx, d.csry, d.keyrow = b[0], b[1], b[2:6]
        elif c.kind == EDIT:
            d.csrx, d.csry, d.lt, d.col0, d.col39 = b[0], b[1], b[2:26], b[26:74:2], b[27:74:2]
        else:
            d.csrx, d.csry, d.lt2, d.cells = b[0], b[1], b[2:4], b[4:9]
        out.append(d)
    return out


if __name__ == "__main__":
    if "--gen" in sys.argv:
        gen()
    else:
        print(f"{len(CASES)} cases, capture {caplen()} B")
