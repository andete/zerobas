"""docs/bios/INITXT.md round 3 (2026-11-17): the XINIT3 supplement, after the second test-writer review of DRAFT 2.
Run 4 of XINIT (xinit_cases.py) gave every case the SAME garbage -- the register copies $A5, CRTCNT 13 -- so a rule
that keeps a bit and a rule that writes a constant could not be told apart (docs/spec-method.md §3a: one garbage
value is itself a constant). XINIT3 varies them. ONE case list that GENERATES probes/bios/spec/xinit3.asm's table
and DECODES its run:

    python3 probes/bios/spec/xinit3_cases.py --gen
    python3 -u probes/bios/biosl_run.py probes/bios/spec/xinit3.asm --row nodisk > scratchpad/XINIT3_run1.out

The setup is XINIT's (xinit_cases.py's docstring), with two inputs per case instead of constants:
  - `rgg`: RG0SAV..RG7SAV := rgg ($A5 as XINIT, $5A, or $A7: R1's size bit set);
  - `crt`: CRTCNT := crt (13 as XINIT, 24, 20, 0, 30);
and `tbl` 2: TXTCOL $2000 / TXTATR $1800, outside every other table (xinit3.asm `tables3`).
One 231-byte record: XINIT's 129 bytes (without its sentinel), then
  the first 40 cells of row CRTCNT (the row clamped to 1..24 for the read),
  LINL40, LINL32, FORCLR, BAKCLR, BDRCLR, TXTNAM .. T32PAT (20 B) read back after the call,
  sum16 of FNKSTR (160 B), sum16 of all 16 KB of VRAM,
  the colour table's 32 bytes at RG3SAV x $40, and the sentinel $C3.
"""
import os
import re
import sys
from types import SimpleNamespace as NS

HERE = os.path.dirname(os.path.abspath(__file__))
ASM = os.path.join(HERE, "xinit3.asm")
INITXT, INIT32 = 0x6C, 0x6F
REC = 231
SENT = 0xC3


def _cases():
    out = []

    def add(call, width, key=0, rgg=0xA5, crt=13, tbl=0, fg=15, bg=4, bd=7):
        name = "INITXT" if call == INITXT else "INIT32"
        out.append(NS(call=call, name=name, width=width, key=key, prior=0, fg=fg, bg=bg, bd=bd, tbl=tbl, vdp=0,
                      rgg=rgg, crt=crt,
                      what=f"{name} width {width} key {'on' if key else 'off'} copies ${rgg:02X} CRTCNT {crt}"
                           + (" tables3" if tbl == 2 else "")))
    for call, w in ((INITXT, 40), (INIT32, 32)):
        for k in (0, 1):
            add(call, w, k, rgg=0x5A)
        add(call, w, 1, rgg=0xA7)
        for crt in (24, 20, 0, 30):
            add(call, w, 1, crt=crt)
        add(call, w, 0, crt=24)
    add(INITXT, 40, 0, tbl=2)
    add(INITXT, 40, 1, tbl=2)
    for w in (33, 34, 35):
        add(INITXT, w, 1)
    for w in (2, 10, 20, 27):
        add(INIT32, w, 1)
    return out


CASES = _cases()


def caplen():
    return 4 + REC * len(CASES)


def table_asm():
    L = ["; ---- GENERATED by xinit3_cases.py --gen: call, width, key, prior, fg, bg, bd, tbl, vdp, rgg, crt; $FF ends ----",
         "cases:"]
    for c in CASES:
        L.append(f"                db      ${c.call:02X}, {c.width}, {c.key}, {c.prior}, {c.fg}, {c.bg}, {c.bd}, {c.tbl}, "
                 f"{c.vdp}, ${c.rgg:02X}, {c.crt}   ; {c.what}")
    L.append("                db      $FF")
    return "\n".join(L) + "\n"


def gen():
    s = open(ASM).read()
    s = s[:s.index("; ---- GENERATED by xinit3_cases.py")] + table_asm()
    s = re.sub(r"; @caplen [0-9A-F]+", f"; @caplen {caplen():04X}", s)
    s = re.sub(r"CAPLEN  equ     \d+", f"CAPLEN  equ     {caplen()}", s)
    open(ASM, "w").write(s)
    print(f"{len(CASES)} cases, capture {caplen()} B")


def decode(block):
    """REFUSES an incomplete block or a record without its sentinel (docs/spec-method.md §3a)."""
    if block[1] != 0xA5:
        sys.exit("FAIL: the XINIT3 block is not complete")
    if len(block) < caplen():
        sys.exit(f"FAIL: the XINIT3 block is {len(block)} B, {caplen()} expected -- the last record has no sentinel")
    out = []
    for i, c in enumerate(CASES):
        b = list(block[4 + REC * i: 4 + REC * (i + 1)])
        if b[REC - 1] != SENT:
            sys.exit(f"FAIL: XINIT3 record {i} has no sentinel")
        w16 = lambda j: b[j] | (b[j + 1] << 8)                      # noqa: E731
        t = b[174:194]
        out.append(NS(**vars(c), idx=i, rg=b[0:8], scrmod=b[8], oldscr=b[9], linlen=b[10], crtcnt=b[11],
                      csrx=b[12], csry=b[13], cnsdfg=b[14], lt=b[15:39], namesum=w16(39), patsum=w16(41),
                      colsum=w16(43), tailsum=w16(45), atrsum=w16(47), lastrow=b[49:89], row13=b[89:129],
                      rowc=b[129:169], linl40=b[169], linl32=b[170], colours=b[171:174],
                      tables=[t[j] | (t[j + 1] << 8) for j in range(0, 20, 2)], fnksum=w16(194), vsum=w16(196),
                      col=b[198:230]))
    return out


if __name__ == "__main__":
    if "--gen" in sys.argv:
        gen()
    else:
        print(f"{len(CASES)} cases, capture {caplen()} B")
