"""docs/bios/CHGET.md round 1 (2026-11-17): the XCHG matrix -- CHGET ($009F) and CHSNS ($009C) on the VG-8020 against
zerobas, with the key buffer FILLED by the probe (no keyboard: what puts keys INTO the buffer is KEYINT's, another
call's page; a waiting CHGET needs a typed key and is a separate keyed probe). ONE case list that GENERATES
probes/bios/spec/xchg.asm's table and DECODES its run:

    python3 probes/bios/spec/xchg_cases.py --gen
    python3 -u probes/bios/biosl_run.py probes/bios/spec/xchg.asm --row nodisk > scratchpad/XCHG_run1.out

The setup, interrupts OFF (no key scan moves the buffer meanwhile), separating:
  - the screen: CNSDFG := 0, then INITXT (mode 0) or INIGRP (mode 2); CSRSW := the case's (0 / 1);
  - garbage: all of VRAM := $5A; KEYBUF ($FBF0, 40 B) := $66 x 40; CSRX := 7, CSRY := 5; A := $5A on entry;
  - the buffer: the case's n codes at KEYBUF + off, off + 1, ... (wrapping at 40); GETPNT := KEYBUF + off,
    PUTPNT := KEYBUF + (off + n) mod 40 -- n = 0 is an empty buffer (CHSNS only: CHGET would wait);
  - interrupts left off (ei 0) or enabled (ei 1) for the call.
Then one 19-byte record: A, F, GETPNT (2), PUTPNT (2), the interrupt state after (LD A,I's flags: bit 2 = IFF2),
CSRX, CSRY, CSRSW, SCRMOD, CNSDFG, sum16 of KEYBUF (2), sum16 of all 16 KB of VRAM (2), the VRAM cells at the
cursor (row 5 column 7) and right of it, and the sentinel $C3.
"""
import os
import re
import sys
from types import SimpleNamespace as NS

HERE = os.path.dirname(os.path.abspath(__file__))
ASM = os.path.join(HERE, "xchg.asm")
CHGET, CHSNS = 0x9F, 0x9C
NAMES = {CHGET: "CHGET", CHSNS: "CHSNS"}
REC = 19
SENT = 0xC3
KEYBUF = 0xFBF0


def _cases():
    raw = []

    def case(call, codes, off=0, csrsw=0, mode=0, ei=0):
        raw.append(NS(call=call, name=NAMES[call], n=len(codes), codes=(list(codes) + [0, 0, 0])[:3], off=off,
                      csrsw=csrsw, mode=mode, ei=ei,
                      what=f"{NAMES[call]} n {len(codes)} codes {' '.join('%02X' % x for x in codes) or '-'} off {off}"
                           f" CSRSW {csrsw} SCREEN {mode}" + (" EI" if ei else "")))
    for csrsw in (0, 1):
        for ei in (0, 1):
            case(CHGET, [0x41], csrsw=csrsw, ei=ei)
    for code in (0x00, 0x01, 0x20, 0x7F, 0xFF):
        case(CHGET, [code])
    case(CHGET, [0x42], off=39)
    case(CHGET, [0x43, 0x44], off=39)
    case(CHGET, [0x41, 0x42, 0x43], off=10)
    case(CHGET, [0x41], mode=2, csrsw=1)
    case(CHSNS, [])
    case(CHSNS, [], off=39, csrsw=1)
    case(CHSNS, [0x41])
    case(CHSNS, [0x00])
    case(CHSNS, [0x41, 0x42, 0x43], off=38)
    case(CHSNS, [0x41], csrsw=1, ei=1)
    case(CHSNS, [], mode=2)
    case(CHSNS, [0x41], mode=2)
    return raw


CASES = _cases()


def caplen():
    return 2 + REC * len(CASES)


def table_asm():
    L = ["; ---- GENERATED by xchg_cases.py --gen: call, n, code x 3, off, CSRSW, mode, ei; $FF ends ----", "cases:"]
    for c in CASES:
        L.append(f"                db      ${c.call:02X}, {c.n}, ${c.codes[0]:02X}, ${c.codes[1]:02X}, ${c.codes[2]:02X}, "
                 f"{c.off}, {c.csrsw}, {c.mode}, {c.ei}   ; {c.what}")
    L.append("                db      $FF")
    return "\n".join(L) + "\n"


def gen():
    s = open(ASM).read()
    s = s[:s.index("; ---- GENERATED by xchg_cases.py")] + table_asm()
    s = re.sub(r"; @caplen [0-9A-F]+", f"; @caplen {caplen():04X}", s)
    s = re.sub(r"CAPLEN  equ     \d+", f"CAPLEN  equ     {caplen()}", s)
    open(ASM, "w").write(s)
    print(f"{len(CASES)} cases, capture {caplen()} B")


def decode(block):
    """REFUSES an incomplete block or a record without its sentinel (docs/spec-method.md §3a)."""
    if block[1] != 0xA5:
        sys.exit("FAIL: the XCHG block is not complete")
    if len(block) < caplen():
        sys.exit(f"FAIL: the XCHG block is {len(block)} B, {caplen()} expected -- the last record has no sentinel")
    out = []
    for i, c in enumerate(CASES):
        b = list(block[2 + REC * i: 2 + REC * (i + 1)])
        if b[REC - 1] != SENT:
            sys.exit(f"FAIL: XCHG record {i} has no sentinel")
        w16 = lambda j: b[j] | (b[j + 1] << 8)                      # noqa: E731
        out.append(NS(**vars(c), idx=i, a=b[0], f=b[1], getpnt=w16(2), putpnt=w16(4), iff=(b[6] >> 2) & 1,
                      csrx=b[7], csry=b[8], csrsw_out=b[9], scrmod=b[10], cnsdfg=b[11], bufsum=w16(12),
                      vsum=w16(14), cur=b[16], cur2=b[17]))
    return out


if __name__ == "__main__":
    if "--gen" in sys.argv:
        gen()
    else:
        print(f"{len(CASES)} cases, capture {caplen()} B")
