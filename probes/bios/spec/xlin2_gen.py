"""docs/bios/PINLIN.md round 2 (2026-11-17): GENERATES the two keyed probes xlin2a.asm / xlin2b.asm from one call list
each, and DECODES their runs. After the first review: INLIN / QINLIN's start ("the screen text from the entry column"
vs "the keys typed"), a gap before the cursor, QINLIN away from column 1, AUTFLG set, and PINLIN's line edges (leading,
inner, trailing spaces, text far right, an empty line, the bottom row's scroll). Two probes because one keyed run
captures at most 255 bytes.

    python3 probes/bios/spec/xlin2_gen.py --gen
    python3 -u probes/bios/biosl_run.py probes/bios/spec/xlin2a.asm --row nodisk > scratchpad/XLIN2A_run1.out
    python3 -u probes/bios/biosl_run.py probes/bios/spec/xlin2b.asm --row nodisk > scratchpad/XLIN2B_run1.out

Each call: BUF ($F55E) filled with $FF (40 bytes), AUTFLG ($F6AA) := the call's, the row's pre-written text through
WRTVRM at its column, CSRX / CSRY := the call's; the keys wait in the buffer (@type-at, one burst at 4 s). Record per
call: the call's own STAGE byte (its number, written after it returned), HL (2), F, CSRX, CSRY, BUF's first NB bytes,
the row's first NR cells; then the sentinel $C3.
"""
import os
import re
import sys
from types import SimpleNamespace as NS

HERE = os.path.dirname(os.path.abspath(__file__))
PINLIN, INLIN, QINLIN = 0xAE, 0xB1, 0xB4
NAMES = {PINLIN: "PINLIN", INLIN: "INLIN", QINLIN: "QINLIN"}

# probe: (NB, NR, calls); a call: (entry, column, row, [(column, text) pre-written], typed, AUTFLG)
PROBES = {
    "a": (16, 12, [(INLIN, 1, 3, [(1, b"XYZ")], b"", 0),
                   (INLIN, 4, 5, [(1, b"XYZWV")], b"Q", 0),
                   (INLIN, 6, 7, [(1, b"XYZ")], b"Q", 0),
                   (QINLIN, 4, 9, [(1, b"XYZ")], b"R", 0),
                   (PINLIN, 4, 11, [(1, b"XYZ")], b"Q", 0xFF),
                   (INLIN, 4, 13, [(1, b"XYZ")], b"Q", 0xFF)]),
    "b": (24, 0, [(PINLIN, 6, 3, [(3, b"XYZ")], b"", 0),
                  (PINLIN, 1, 5, [], b"A B  ", 0),
                  (PINLIN, 4, 7, [(1, b"XYZ"), (18, b"W")], b"", 0),
                  (PINLIN, 1, 9, [], b"", 0),
                  (PINLIN, 1, 24, [], b"AB", 0)]),
}


def reclen(p):
    nb, nr, _ = PROBES[p]
    return 6 + nb + nr


def calls(p):
    return [NS(entry=e, name=NAMES[e], x=x, y=y, pre=pre, typed=t, autflg=a) for e, x, y, pre, t, a in PROBES[p][2]]


def asm(p):
    nb, nr, cl = PROBES[p]
    keys = "".join(t.decode().replace(" ", " ") + "\\r" for _, _, _, _, t, _ in cl)
    L = [f"""; Copyright (c) 2026 Joost Yervante Damad
; SPDX-License-Identifier: 0BSD
;
; XLIN2{p.upper()} -- docs/bios/PINLIN.md round 2 (2026-11-17). GENERATED by probes/bios/spec/xlin2_gen.py (--gen), whose
; docstring documents the calls, the setup and the record; the same module decodes the run.
; Run: python3 -u probes/bios/biosl_run.py probes/bios/spec/xlin2{p}.asm --row nodisk
;
; CLEAN-ROOM: 100% own code; only published BIOS entries and work-area cells; VRAM through RDVRM / WRTVRM.
;
; @cap C000
; @type-at 4 {keys}
; @timeout 60

RDVRM   equ     $004A
WRTVRM  equ     $004D
INITXT  equ     $006C
LINL40  equ     $F3AE
CSRY    equ     $F3DC
CSRX    equ     $F3DD
CNSDFG  equ     $F3DE
CSRSW   equ     $FCA9
BUF     equ     $F55E
AUTFLG  equ     $F6AA
NB      equ     {nb}
NR      equ     {nr}

DONE    equ     $C000
CAP     equ     $C001
ptr     equ     $EF00
crow    equ     $EF02
rHL     equ     $EF04
rF      equ     $EF06
cnum    equ     $EF07

                org     $4000
                db      "AB"
                dw      init, 0, 0, 0
                ds      6, 0

init:
                ld      hl, CAP
                ld      de, CAP+1
                ld      bc, $FE
                ld      (hl), 0
                ldir
                xor     a
                ld      (CNSDFG), a
                ld      (CSRSW), a
                ld      (cnum), a
                ld      a, 40
                ld      (LINL40), a
                call    INITXT
                ld      hl, CAP
                ld      (ptr), hl
                ld      ix, calls
c_lp:
                ld      a, (ix+0)
                cp      $FF
                jp      z, c_done
                ld      a, (ix+3)
                ld      (crow), a
                ld      a, (ix+4)
                ld      (AUTFLG), a
                ld      hl, BUF
                ld      b, 40
c_bf:
                ld      (hl), $FF
                inc     hl
                djnz    c_bf
                ; pre-written text: (ix+5..6) -> a list of (column, length, bytes...), 0 ends
                ld      l, (ix+5)
                ld      h, (ix+6)
c_pre:
                ld      a, (hl)
                or      a
                jr      z, c_go
                push    hl
                call    rowcol                  ; DE := the name-table address of (crow, A)
                pop     hl
                inc     hl
                ld      b, (hl)
                inc     hl
c_pw:
                ld      a, (hl)
                push    hl
                push    de
                ex      de, hl
                call    WRTVRM
                pop     de
                pop     hl
                inc     de
                inc     hl
                djnz    c_pw
                jr      c_pre
c_go:
                ld      a, (ix+2)
                ld      (CSRX), a
                ld      a, (crow)
                ld      (CSRY), a
                ld      l, (ix+0)
                ld      h, 0
                push    ix
                call    jphl
                push    af
                pop     bc
                ld      (rHL), hl
                ld      a, c
                ld      (rF), a
                pop     ix
                ld      a, (cnum)
                inc     a
                ld      (cnum), a
                call    emit                    ; the call's own STAGE byte
                ld      hl, (rHL)
                ld      a, l
                call    emit
                ld      a, h
                call    emit
                ld      a, (rF)
                call    emit
                ld      a, (CSRX)
                call    emit
                ld      a, (CSRY)
                call    emit
                ld      hl, BUF
                ld      b, NB
c_rb:
                ld      a, (hl)
                call    emit
                inc     hl
                djnz    c_rb
                ld      b, NR
                ld      a, b
                or      a
                jr      z, c_nr
                push    bc
                ld      a, 1
                call    rowcol
                pop     bc
                ex      de, hl
c_rr:
                push    bc
                push    hl
                call    RDVRM
                call    emit
                pop     hl
                pop     bc
                inc     hl
                djnz    c_rr
c_nr:
                ld      de, 7
                add     ix, de
                jp      c_lp
c_done:
                ld      a, $C3
                call    emit
                ld      a, $A5
                ld      (DONE), a
halt_lp:
                jr      halt_lp

jphl:
                jp      (hl)

; rowcol -- DE := the name-table address of row (crow), column A (both 1-based), 40 columns
rowcol:
                dec     a
                ld      e, a
                ld      d, 0
                ld      a, (crow)
                ld      b, a
                ld      hl, 40
r_lp:
                dec     b
                jr      z, r_done
                ex      de, hl
                add     hl, de
                ex      de, hl
                jr      r_lp
r_done:
                ret

emit:
                push    hl
                ld      hl, (ptr)
                ld      (hl), a
                inc     hl
                ld      (ptr), hl
                pop     hl
                ret

; per call: entry (low byte; the high is 0), unused, CSRX, CSRY, AUTFLG, the pre-written list's address; $FF ends
calls:"""]
    pres = []
    for i, (e, x, y, pre, t, a) in enumerate(cl):
        L.append(f"                db      ${e:02X}, 0, {x}, {y}, ${a:02X}")
        L.append(f"                dw      pre{i}")
        pres.append(f"pre{i}:" + "".join(f"\n                db      {c}, {len(txt)}, " + ", ".join(f"${b:02X}" for b in txt)
                                         for c, txt in pre) + "\n                db      0")
    L.append("                db      $FF")
    L += pres
    return "\n".join(L) + "\n"


def gen():
    for p in PROBES:
        open(os.path.join(HERE, f"xlin2{p}.asm"), "w").write(asm(p))
        print(f"xlin2{p}.asm: {len(PROBES[p][2])} calls, capture {len(PROBES[p][2]) * reclen(p) + 1} B")


def decode(p, block):
    """REFUSES a block without the sentinel after the last call, or a call whose STAGE byte is not its number."""
    n, rl = len(PROBES[p][2]), reclen(p)
    nb, nr, _ = PROBES[p]
    if len(block) < n * rl + 1 or block[n * rl] != 0xC3:
        sys.exit(f"FAIL: the XLIN2{p.upper()} block has no sentinel after {n} calls")
    out = []
    for i, c in enumerate(calls(p)):
        b = list(block[rl * i: rl * (i + 1)])
        if b[0] != i + 1:
            sys.exit(f"FAIL: XLIN2{p.upper()} call {i + 1}'s STAGE byte is {b[0]}")
        out.append(NS(**vars(c), idx=i + 1, stage=b[0], hl=b[1] | (b[2] << 8), f=b[3], csrx=b[4], csry=b[5],
                      buf=b[6:6 + nb], row=b[6 + nb:6 + nb + nr]))
    return out


if __name__ == "__main__":
    if "--gen" in sys.argv:
        gen()
