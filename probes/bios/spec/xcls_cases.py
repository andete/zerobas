"""docs/bios/CLS.md round 1 (2026-11-17): the XCLS matrix -- CLS ($00C3) and POSIT ($00C6) on the VG-8020 against
zerobas. ONE case list that GENERATES the probe's case table (probes/bios/spec/xcls.asm) and DECODES its run.

    python3 probes/bios/spec/xcls_cases.py --gen
    python3 -u probes/bios/biosl_run.py probes/bios/spec/xcls.asm --row nodisk > scratchpad/XCLS_run2.out

The setup SEPARATES (docs/spec-method.md §3a), and does not use the calls under test:
  - the screen: CNSDFG := 0, CRTCNT := 24, the width cell := the case's width, then INITXT (mode 0), INIT32
    (mode 1) or INIGRP (mode 2) (docs/bios/INITXT.md);
  - then LINL40 := LINL32 := 77; FNKSTR := "key0".."key9"; FORCLR / BAKCLR / BDRCLR := 11 / 6 / 13 or (colours 1) $3A / $C5 / $F9;
    CRTCNT := the case's (24 / 13), CNSDFG := the case's (0 / 1);
  - garbage: ALL of VRAM := $5A (FILVRM), LINTTB := $55 x 24, CSRX := 7, CSRY := 5;
  - the call through a RAM `JP`, with H / L := the case's (POSIT's column / row; for CLS 99 / 99) and the Z flag
    set (zf 1) or clear (zf 0) by a `cp` just before it (A = zf).
Then one 159-byte record:
  CNSDFG, CRTCNT, CSRX, CSRY, LINLEN, SCRMOD (6), LINTTB (24), sum16 of the name table (960 B at $0000 in
  mode 0, 768 B at $1800 otherwise) (2), 40 cells from row 1's, row CRTCNT's and row 24's starts (120),
  sum16 of VRAM $0000-$07FF, of $2000-$27FF, and of all 16 KB (6), and the sentinel $C3.
"""
import os
import re
import sys
from types import SimpleNamespace as NS

HERE = os.path.dirname(os.path.abspath(__file__))
ASM = os.path.join(HERE, "xcls.asm")
CLS, POSIT = 0xC3, 0xC6
NAMES = {CLS: "CLS", POSIT: "POSIT"}
REC = 159
SENT = 0xC3


def _cases():
    out = []

    def add(call, mode=0, width=40, cns=0, crt=24, zf=1, h=99, l=99, col=0):     # noqa: E741
        what = (f"{NAMES[call]} SCREEN {mode} width {width} CNSDFG {cns} CRTCNT {crt}"
                + (f" Z {'set' if zf else 'clear'}" if call == CLS else f" H {h} L {l}")
                + (" colours 58,197,249" if col else ""))
        out.append(NS(call=call, name=NAMES[call], mode=mode, width=width, cns=cns, crt=crt, zf=zf, h=h, l=l,
                      col=col, fg=(11, 0x3A)[col], bg=(6, 0xC5)[col], what=what))
    for cns in (0, 1):
        for zf in (1, 0):
            add(CLS, 0, 40, cns, zf=zf)
    add(CLS, 0, 37, 1)
    add(CLS, 0, 39, 0)
    for cns in (0, 1):
        add(CLS, 0, 40, cns, crt=13)
        add(CLS, 1, 32, cns)
    add(CLS, 1, 29, 1)
    add(CLS, 1, 32, 0, zf=0)
    add(CLS, 2, 32, 0)
    add(CLS, 2, 32, 0, zf=0)
    add(CLS, 2, 32, 1)
    for h, l in ((1, 1), (40, 24), (0, 0), (41, 25), (255, 255), (20, 13)):  # noqa: E741
        add(POSIT, 0, 40, h=h, l=l)
    add(POSIT, 0, 37, h=37, l=24)
    add(POSIT, 0, 37, h=38, l=1)
    add(POSIT, 1, 32, h=32, l=24)
    add(POSIT, 1, 32, h=33, l=24)
    add(POSIT, 2, 32, h=5, l=5)
    add(POSIT, 0, 40, cns=1, h=1, l=24)
    # run 2: separating values (run 1's clamp to 24 could be CRTCNT's 24; its SCREEN 2 L equalled CSRY's garbage)
    for h, l in ((0, 0), (20, 20), (41, 14), (39, 13)):  # noqa: E741
        add(POSIT, 0, 40, crt=13, h=h, l=l)
    add(POSIT, 0, 37, h=0, l=30)
    add(POSIT, 1, 29, h=31, l=2)
    add(POSIT, 1, 29, h=30, l=24)
    add(POSIT, 2, 32, h=3, l=9)
    add(POSIT, 2, 32, h=0, l=0)
    add(CLS, 2, 32, 0, col=1)
    add(CLS, 0, 40, 1, col=1)
    add(CLS, 1, 32, 0, col=1)
    return out


CASES = _cases()


def caplen():
    return 2 + REC * len(CASES)


def table_asm():
    L = ["; ---- GENERATED by xcls_cases.py --gen: call, mode, width, CNSDFG, CRTCNT, zf, H, L, colours; $FF ends ----",
         "cases:"]
    for c in CASES:
        L.append(f"                db      ${c.call:02X}, {c.mode}, {c.width}, {c.cns}, {c.crt}, {c.zf}, {c.h}, {c.l}, "
                 f"{c.col}   ; {c.what}")
    L.append("                db      $FF")
    return "\n".join(L) + "\n"


def gen():
    s = open(ASM).read()
    s = s[:s.index("; ---- GENERATED by xcls_cases.py")] + table_asm()
    s = re.sub(r"; @caplen [0-9A-F]+", f"; @caplen {caplen():04X}", s)
    s = re.sub(r"CAPLEN  equ     \d+", f"CAPLEN  equ     {caplen()}", s)
    open(ASM, "w").write(s)
    print(f"{len(CASES)} cases, capture {caplen()} B")


def decode(block):
    """REFUSES an incomplete block or a record without its sentinel (docs/spec-method.md §3a)."""
    if block[1] != 0xA5:
        sys.exit("FAIL: the XCLS block is not complete")
    if len(block) < caplen():
        sys.exit(f"FAIL: the XCLS block is {len(block)} B, {caplen()} expected -- the last record has no sentinel")
    out = []
    for i, c in enumerate(CASES):
        b = list(block[2 + REC * i: 2 + REC * (i + 1)])
        if b[REC - 1] != SENT:
            sys.exit(f"FAIL: XCLS record {i} has no sentinel")
        w16 = lambda j: b[j] | (b[j + 1] << 8)                      # noqa: E731
        out.append(NS(**vars(c), idx=i, cnsdfg=b[0], crtcnt=b[1], csrx=b[2], csry=b[3], linlen=b[4], scrmod=b[5],
                      lt=b[6:30], namesum=w16(30), row1=b[32:72], rowc=b[72:112], row24=b[112:152],
                      sum0=w16(152), sum2=w16(154), vsum=w16(156)))
    return out


if __name__ == "__main__":
    if "--gen" in sys.argv:
        gen()
    else:
        print(f"{len(CASES)} cases, capture {caplen()} B")
