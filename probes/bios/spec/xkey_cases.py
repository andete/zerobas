"""docs/bios/DSPFNK.md round 1 (2026-11-17): the XKEY matrix -- DSPFNK ($00CF), ERAFNK ($00CC) and FNKSB ($00C9) on
the VG-8020 against zerobas. ONE case list that GENERATES the probe's case table (probes/bios/spec/xkey.asm) and
DECODES its run.

    python3 probes/bios/spec/xkey_cases.py --gen
    python3 -u probes/bios/biosl_run.py probes/bios/spec/xkey.asm --row nodisk > scratchpad/XKEY_run1.out

The setup SEPARATES (docs/spec-method.md §3a), and does not use the calls under test:
  - the screen: CNSDFG := 0, CRTCNT := 24, the width cell := the case's width, then INITXT (mode 0), INIT32
    (mode 1) or INIGRP (mode 2) -- INITXT / INIT32 are specified (docs/bios/INITXT.md) and with the key line
    off they only clear;
  - then LINL40 := LINL32 := 77, so the width the call uses is LINLEN's, not the cell's;
  - FNKSTR := the case's label set: 0 = "key0".."key9"; 1 = odd labels (key 1 fifteen characters, key 2
    with a $01 graphic prefix, key 3 with a CR, key 4 empty, key 5 with DEL and ESC Y, keys 6-10 "k5".."k9");
  - FNKFLG (10 B at $FBCE) := the case's flag byte in all 10;
  - CRTCNT := the case's row count (24 or 13), CNSDFG := the case's flag (0, 1, $80);
  - the name table filled with $5A (FILVRM, not under test), CSRX := 7, CSRY := 5 (garbage).
Then the call, and one 129-byte record:
  CNSDFG, CRTCNT, CSRX, CSRY, LINLEN, SCRMOD (6), sum16 of the name table (960 / 768 B) (2),
  40 cells from row 24's start, 40 from row CRTCNT's, 40 from row CRTCNT-1's (rows 40 / 32 cells wide),
  and the sentinel $C3. A decoder refuses a record without it.
"""
import os
import re
import sys
from types import SimpleNamespace as NS

HERE = os.path.dirname(os.path.abspath(__file__))
ASM = os.path.join(HERE, "xkey.asm")
DSPFNK, ERAFNK, FNKSB = 0xCF, 0xCC, 0xC9
NAMES = {DSPFNK: "DSPFNK", ERAFNK: "ERAFNK", FNKSB: "FNKSB"}
REC = 129
SENT = 0xC3


def _cases():
    out = []

    def add(call, mode=0, width=40, cns=0, crt=24, flg=0, lab=0):
        what = (f"{NAMES[call]} SCREEN {mode} width {width} CNSDFG {cns} CRTCNT {crt}"
                + (f" FNKFLG {flg}" if flg else "") + (" odd labels" if lab else ""))
        out.append(NS(call=call, name=NAMES[call], mode=mode, width=width, cns=cns, crt=crt, flg=flg, lab=lab,
                      what=what))
    for call in (DSPFNK, ERAFNK, FNKSB):
        for cns in (0, 1, 0x80):
            add(call, 0, 40, cns)
        for w in (37, 39):
            add(call, 0, w, 1)
        for w in (32, 29):
            for cns in (0, 1):
                add(call, 1, w, cns)
        for cns in (0, 1):
            add(call, 0, 40, cns, crt=13)
            add(call, 2, 32, cns)
    for cns in (0, 1):
        for flg in (1, 0xFF):
            add(FNKSB, 0, 40, cns, flg=flg)
    add(DSPFNK, 0, 40, 0, lab=1)
    add(DSPFNK, 1, 32, 0, lab=1)
    add(DSPFNK, 0, 40, 1, lab=1)
    return out


CASES = _cases()


def caplen():
    return 2 + REC * len(CASES)


def table_asm():
    L = ["; ---- GENERATED by xkey_cases.py --gen: call, mode, width, CNSDFG, CRTCNT, FNKFLG, labels; $FF ends ----",
         "cases:"]
    for c in CASES:
        L.append(f"                db      ${c.call:02X}, {c.mode}, {c.width}, {c.cns}, {c.crt}, {c.flg}, {c.lab}"
                 f"   ; {c.what}")
    L.append("                db      $FF")
    return "\n".join(L) + "\n"


def gen():
    s = open(ASM).read()
    s = s[:s.index("; ---- GENERATED by xkey_cases.py")] + table_asm()
    s = re.sub(r"; @caplen [0-9A-F]+", f"; @caplen {caplen():04X}", s)
    s = re.sub(r"CAPLEN  equ     \d+", f"CAPLEN  equ     {caplen()}", s)
    open(ASM, "w").write(s)
    print(f"{len(CASES)} cases, capture {caplen()} B")


def decode(block):
    """REFUSES an incomplete block or a record without its sentinel (docs/spec-method.md §3a)."""
    if block[1] != 0xA5:
        sys.exit("FAIL: the XKEY block is not complete")
    if len(block) < caplen():
        sys.exit(f"FAIL: the XKEY block is {len(block)} B, {caplen()} expected -- the last record has no sentinel")
    out = []
    for i, c in enumerate(CASES):
        b = list(block[2 + REC * i: 2 + REC * (i + 1)])
        if b[REC - 1] != SENT:
            sys.exit(f"FAIL: XKEY record {i} has no sentinel")
        out.append(NS(**vars(c), idx=i, cnsdfg=b[0], crtcnt=b[1], csrx=b[2], csry=b[3], linlen=b[4], scrmod=b[5],
                      namesum=b[6] | (b[7] << 8), row24=b[8:48], rowc=b[48:88], rowc1=b[88:128]))
    return out


if __name__ == "__main__":
    if "--gen" in sys.argv:
        gen()
    else:
        print(f"{len(CASES)} cases, capture {caplen()} B")
