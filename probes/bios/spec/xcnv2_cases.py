"""docs/bios/CNVCHR.md round 2 (2026-11-17): the XCNV2 supplement, after the first review. XCNV's probe left HL pointing
at a copy of the GRPHED value and D equal to A in every case, its GRPHED values were only 0 / 1 / $5A (bits 2, 5, 7
never set) and its entry flags only $00 / $FF; and the natural sequence -- the header, then the character, with
GRPHED left by the routine itself -- was never run. ONE case list that GENERATES probes/bios/spec/xcnv2.asm's table and
DECODES its run:

    python3 probes/bios/spec/xcnv2_cases.py --gen
    python3 -u probes/bios/biosl_run.py probes/bios/spec/xcnv2.asm --row nodisk > scratchpad/XCNV2_run2.out

Per call, every register is garbage UNLIKE the inputs: BC $1357, D $9B (never A), E $DF, IX $4321, IY $8765, and HL
pointing at a RAM byte holding the OPPOSITE of GRPHED's zero-ness (GRPHED 0: the byte is 1; else 0); interrupts off.
A "seq" case calls CNVCHR($01) with GRPHED := 0 and then CNVCHR(A) WITHOUT writing GRPHED, and records both calls.
One 18-byte record per call: A, F, B, C, D, E, H, L, IXh, IXl, IYh, IYl, GRPHED, the HL byte, LD A,I's flags (bit 2 =
IFF2), the work-area bytes changed outside GRPHED ($F380-$FFFF, 2), and the sentinel $C3.
"""
import os
import re
import sys
from types import SimpleNamespace as NS

HERE = os.path.dirname(os.path.abspath(__file__))
ASM = os.path.join(HERE, "xcnv2.asm")
REC = 18
SENT = 0xC3


def _cases():
    out = []
    for g in (0x80, 0xFF, 0x20, 0x04):
        for a in (0x01, 0x40, 0x5F, 0x3F, 0x60):
            out.append(NS(seq=0, a=a, g=g, f=0x00, what=f"A {a:02X} GRPHED {g:02X} F 00"))
    for f in (0x01, 0x40, 0x41, 0x80, 0x04, 0x10, 0x55, 0xAA):
        for a, g in ((0x01, 0), (0x40, 1), (0x60, 1)):
            out.append(NS(seq=0, a=a, g=g, f=f, what=f"A {a:02X} GRPHED {g:02X} F {f:02X}"))
    for a in (0x3F, 0x40, 0x5F, 0x60, 0x01):
        out.append(NS(seq=1, a=a, g=0, f=0x00, what=f"CNVCHR(01) then CNVCHR({a:02X}), GRPHED left by the first"))
    # run 2 (the confirming pass): the plain-character path -- GRPHED 0, A not $01 -- with every register garbage
    for a in (0x00, 0x3F, 0x40, 0x5F, 0x60, 0xFF):
        out.append(NS(seq=0, a=a, g=0, f=0x00, what=f"A {a:02X} GRPHED 00 F 00 (plain path)"))
    return out


CASES = _cases()


def records():
    return sum(2 if c.seq else 1 for c in CASES)


def caplen():
    return 2 + REC * records()


def table_asm():
    L = ["; ---- GENERATED by xcnv2_cases.py --gen: seq, A, GRPHED, F; $FF ends ----", "cases:"]
    for c in CASES:
        L.append(f"                db      {c.seq}, ${c.a:02X}, ${c.g:02X}, ${c.f:02X}   ; {c.what}")
    L.append("                db      $FF")
    return "\n".join(L) + "\n"


def gen():
    s = open(ASM).read()
    s = s[:s.index("; ---- GENERATED by xcnv2_cases.py")] + table_asm()
    s = re.sub(r"; @caplen [0-9A-F]+", f"; @caplen {caplen():04X}", s)
    s = re.sub(r"CAPLEN  equ     \d+", f"CAPLEN  equ     {caplen()}", s)
    open(ASM, "w").write(s)
    print(f"{len(CASES)} cases, {records()} records, capture {caplen()} B")


def decode(block):
    """REFUSES an incomplete block or a record without its sentinel. A seq case gives two calls: the header (.first)
    and the character (the case itself)."""
    if block[1] != 0xA5 or len(block) < caplen():
        sys.exit("FAIL: the XCNV2 block is not complete")
    out, k = [], 0

    def rec():
        nonlocal k
        b = list(block[2 + REC * k: 2 + REC * (k + 1)])
        k += 1
        if b[REC - 1] != SENT:
            sys.exit(f"FAIL: XCNV2 record {k - 1} has no sentinel")
        return dict(a_out=b[0], f_out=b[1], bc=(b[2] << 8) | b[3], de=(b[4] << 8) | b[5], hl=(b[6] << 8) | b[7],
                    ix=(b[8] << 8) | b[9], iy=(b[10] << 8) | b[11], grphed=b[12], hlbyte=b[13], iff=(b[14] >> 2) & 1,
                    nchg=b[15] | (b[16] << 8))
    for i, c in enumerate(CASES):
        first = rec() if c.seq else None
        out.append(NS(**vars(c), idx=i, first=first, **rec()))
    return out


if __name__ == "__main__":
    if "--gen" in sys.argv:
        gen()
    else:
        print(f"{len(CASES)} cases, {records()} records, capture {caplen()} B")
