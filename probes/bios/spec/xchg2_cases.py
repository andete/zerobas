"""docs/bios/CHGET.md round 2 (2026-11-17): the XCHG2 supplement, after the first review. XCHG's (GETPNT offset, codes
waiting) pairs coincided (offset 0 only with 1 code, 10 only with 3), so CHGET's flags could be read as "codes waiting"
or as a compare on GETPNT's new low byte; entry F followed the interrupt choice; entry A equalled the VRAM garbage;
CNSDFG was always 0; "nothing else" read only a few cells. ONE case list that GENERATES probes/bios/spec/xchg2.asm's
table and DECODES its run:

    python3 probes/bios/spec/xchg2_cases.py --gen
    python3 -u probes/bios/biosl_run.py probes/bios/spec/xchg2.asm --row nodisk > scratchpad/XCHG2_run1.out

The setup: CNSDFG := the case's (0 / 1), LINL40 := 40, INITXT (docs/bios/INITXT.md); interrupts off; all of VRAM :=
$5A; KEYBUF := $66 x 40, the bytes either side of it := $A5; the case's n codes from KEYBUF + off; GETPNT / PUTPNT as
xchg_cases.py; CSRX / CSRY := the case's; CSRSW := 1; every register garbage (BC $1357, DE $9BDF, HL $2468, IX $4321,
IY $8765), A := $A7 (unlike the VRAM garbage), F := the case's (POP AF), interrupts off or on (`ei`) independently;
the work area $F380-$FFFF copied to $D000 before the call. One 83-byte record: A, F, B, C, D, E, H, L, IXh, IXl, IYh,
IYl, LD A,I's flags (bit 2 = IFF2), GETPNT low, PUTPNT low, CSRX, CSRY, CSRSW, CNSDFG, LINLEN, KEYBUF's 40 bytes and
the one before / after it, sum16 of all 16 KB of VRAM, the number of work-area bytes changed outside GETPNT / PUTPNT /
KEYBUF and the interrupt's cells ($F3F6-$F3F7, $FC9E-$FCA2) (2) and the first eight such addresses (16), the sentinel.
"""
import os
import re
import sys
from types import SimpleNamespace as NS

HERE = os.path.dirname(os.path.abspath(__file__))
ASM = os.path.join(HERE, "xchg2.asm")
CHGET, CHSNS = 0x9F, 0x9C
NAMES = {CHGET: "CHGET", CHSNS: "CHSNS"}
REC = 83
SENT = 0xC3


def _cases():
    out = []

    def case(call, codes, off, f=0x00, ei=0, cns=0, x=7, y=5):
        out.append(NS(call=call, name=NAMES[call], n=len(codes), codes=(list(codes) + [0, 0, 0])[:3], off=off, f=f,
                      ei=ei, cns=cns, x=x, y=y,
                      what=f"{NAMES[call]} n {len(codes)} off {off} F {f:02X}" + (" EI" if ei else "")
                           + (" CNSDFG 1" if cns else "") + (f" cursor {x},{y}" if (x, y) != (7, 5) else "")))
    # the flag readings disagree: codes waiting vs the new GETPNT low byte
    case(CHGET, [0x41, 0x42, 0x43], 0)
    case(CHGET, [0x41], 10)
    case(CHGET, [0x41], 5)
    case(CHGET, [0x41, 0x42], 20)
    case(CHGET, [0x41, 0x42], 38)
    case(CHGET, [0x41], 23)
    case(CHGET, [0x41], 24)
    # entry flags and the interrupt choice independent; CNSDFG 1; another cursor
    case(CHGET, [0x41], 0, f=0xFF, ei=0)
    case(CHGET, [0x41], 0, f=0x00, ei=1)
    case(CHGET, [0x41], 0, cns=1, x=1, y=24)
    case(CHSNS, [0x41, 0x42, 0x43], 0, f=0xFF)
    case(CHSNS, [], 10, f=0xFF, ei=1)
    case(CHSNS, [0x41], 23, cns=1, x=1, y=24)
    case(CHSNS, [0x41, 0x42], 39)
    return out


CASES = _cases()


def caplen():
    return 2 + REC * len(CASES)


def table_asm():
    L = ["; ---- GENERATED by xchg2_cases.py --gen: call, n, code x 3, off, F, ei, CNSDFG, CSRX, CSRY; $FF ends ----",
         "cases:"]
    for c in CASES:
        L.append(f"                db      ${c.call:02X}, {c.n}, ${c.codes[0]:02X}, ${c.codes[1]:02X}, ${c.codes[2]:02X}, "
                 f"{c.off}, ${c.f:02X}, {c.ei}, {c.cns}, {c.x}, {c.y}   ; {c.what}")
    L.append("                db      $FF")
    return "\n".join(L) + "\n"


def gen():
    s = open(ASM).read()
    s = s[:s.index("; ---- GENERATED by xchg2_cases.py")] + table_asm()
    s = re.sub(r"; @caplen [0-9A-F]+", f"; @caplen {caplen():04X}", s)
    s = re.sub(r"CAPLEN  equ     \d+", f"CAPLEN  equ     {caplen()}", s)
    open(ASM, "w").write(s)
    print(f"{len(CASES)} cases, capture {caplen()} B")


def decode(block):
    if block[1] != 0xA5 or len(block) < caplen():
        sys.exit("FAIL: the XCHG2 block is not complete")
    out = []
    for i, c in enumerate(CASES):
        b = list(block[2 + REC * i: 2 + REC * (i + 1)])
        if b[REC - 1] != SENT:
            sys.exit(f"FAIL: XCHG2 record {i} has no sentinel")
        w = lambda j: (b[j] << 8) | b[j + 1]                        # noqa: E731
        n = b[64] | (b[65] << 8)
        out.append(NS(**vars(c), idx=i, a=b[0], f_out=b[1], bc=w(2), de=w(4), hl=w(6), ix=w(8), iy=w(10),
                      iff=(b[12] >> 2) & 1, getlo=b[13], putlo=b[14], csrx=b[15], csry=b[16], csrsw=b[17],
                      cnsdfg=b[18], linlen=b[19], keybuf=b[20:60], before=b[60], after=b[61], vsum=b[62] | (b[63] << 8),
                      nchg=n, chg=[b[66 + 2 * k] | (b[67 + 2 * k] << 8) for k in range(min(n, 8))]))
    return out


if __name__ == "__main__":
    if "--gen" in sys.argv:
        gen()
    else:
        print(f"{len(CASES)} cases, capture {caplen()} B")
