"""docs/bios/TOTEXT.md round 1 (2026-11-17): the XTOT matrix -- TOTEXT ($00D2) on the VG-8020 against zerobas. ONE case
list that GENERATES probes/bios/spec/xtot.asm's table and DECODES its run:

    python3 probes/bios/spec/xtot_cases.py --gen
    python3 -u probes/bios/biosl_run.py probes/bios/spec/xtot.asm --row nodisk > scratchpad/XTOT_run1.out

The setup: CNSDFG := 0, LINL40 := 40, LINL32 := 32, then INITXT / INIT32 / INIGRP / INIMLT (SCRMOD 0..3 on entry);
then, separating: OLDSCR := the case's (0, 1, or garbage $5A); LINL40 := 37, LINL32 := 29 (the width shows which screen
TOTEXT set up); CNSDFG := the case's (0 / 1); CRTCNT := 24; all of VRAM := $5A; CSRX := 7, CSRY := 5. The register
copies RG0SAV..RG7SAV stay as the mode's call set them. Then TOTEXT, and one 22-byte record: RG0SAV..RG7SAV, SCRMOD,
OLDSCR, LINLEN, CRTCNT, CSRX, CSRY, CNSDFG, sum16 of VRAM $0000-$03BF (SCREEN 0's name table), sum16 of $1800-$1AFF
(SCREEN 1's), sum16 of all 16 KB, and the sentinel $C3.
"""
import os
import re
import sys
from types import SimpleNamespace as NS

HERE = os.path.dirname(os.path.abspath(__file__))
ASM = os.path.join(HERE, "xtot.asm")
REC = 22
SENT = 0xC3


def _cases():
    out = []
    for mode in (0, 1, 2, 3):
        for old in (0, 1, 0x5A):
            for cns in (0, 1):
                out.append(NS(mode=mode, old=old, cns=cns,
                              what=f"TOTEXT from SCREEN {mode} OLDSCR {old:#04x} CNSDFG {cns}"))
    return out


CASES = _cases()


def caplen():
    return 2 + REC * len(CASES)


def table_asm():
    L = ["; ---- GENERATED by xtot_cases.py --gen: mode, OLDSCR, CNSDFG; $FF ends ----", "cases:"]
    for c in CASES:
        L.append(f"                db      {c.mode}, ${c.old:02X}, {c.cns}   ; {c.what}")
    L.append("                db      $FF")
    return "\n".join(L) + "\n"


def gen():
    s = open(ASM).read()
    s = s[:s.index("; ---- GENERATED by xtot_cases.py")] + table_asm()
    s = re.sub(r"; @caplen [0-9A-F]+", f"; @caplen {caplen():04X}", s)
    s = re.sub(r"CAPLEN  equ     \d+", f"CAPLEN  equ     {caplen()}", s)
    open(ASM, "w").write(s)
    print(f"{len(CASES)} cases, capture {caplen()} B")


def decode(block):
    """REFUSES an incomplete block or a record without its sentinel (docs/spec-method.md §3a)."""
    if block[1] != 0xA5:
        sys.exit("FAIL: the XTOT block is not complete")
    if len(block) < caplen():
        sys.exit(f"FAIL: the XTOT block is {len(block)} B, {caplen()} expected -- the last record has no sentinel")
    out = []
    for i, c in enumerate(CASES):
        b = list(block[2 + REC * i: 2 + REC * (i + 1)])
        if b[REC - 1] != SENT:
            sys.exit(f"FAIL: XTOT record {i} has no sentinel")
        w16 = lambda j: b[j] | (b[j + 1] << 8)                      # noqa: E731
        out.append(NS(**vars(c), idx=i, rg=b[0:8], scrmod=b[8], oldscr=b[9], linlen=b[10], crtcnt=b[11],
                      csrx=b[12], csry=b[13], cnsdfg=b[14], sum40=w16(15), sum32=w16(17), vsum=w16(19)))
    return out


if __name__ == "__main__":
    if "--gen" in sys.argv:
        gen()
    else:
        print(f"{len(CASES)} cases, capture {caplen()} B")
