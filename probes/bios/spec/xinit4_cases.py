"""docs/bios/INITXT.md round 4 (2026-11-17): the XINIT4 supplement, after the THIRD review. XINIT3's register-copy
garbage ($A5 / $5A / $A7) changed bits 7, 5, 2 and 0 together, so the per-bit "kept" claims were not pinned; the
whole-VRAM sum was never taken at widths 0 / 80 / 255 with the key line on or for INIT32 with moved tables; VRAM's
garbage was always $5A; the labels never longer than 4. XINIT4 is XINIT3's probe with two more case fields -- `fill`
(the VRAM garbage byte) and `lab` (1: 7-character labels "ABCDEF0".."ABCDEF9") -- and walking-bit copies. XINIT3's
docstring follows.

docs/bios/INITXT.md round 3 (2026-11-17): the XINIT3 supplement, after the second test-writer review of DRAFT 2.
Run 4 of XINIT (xinit_cases.py) gave every case the SAME garbage -- the register copies $A5, CRTCNT 13 -- so a rule
that keeps a bit and a rule that writes a constant could not be told apart (docs/spec-method.md §3a: one garbage
value is itself a constant). XINIT3 varies them. ONE case list that GENERATES probes/bios/spec/xinit3.asm's table
and DECODES its run:

    python3 probes/bios/spec/xinit4_cases.py --gen
    python3 -u probes/bios/biosl_run.py probes/bios/spec/xinit4.asm --row nodisk > scratchpad/XINIT4_run4.out

The setup is XINIT's (xinit_cases.py's docstring), with two inputs per case instead of constants:
  - `rgg`: RG0SAV..RG7SAV := rgg ($A5 as XINIT, $5A, or $A7: R1's size bit set);
  - `crt`: CRTCNT := crt (13 as XINIT, 24, 20, 0, 30);
and `tbl` 2: TXTCOL $2000 / TXTATR $1800, outside every other table (xinit3.asm `tables3`).
One 231-byte record: XINIT's 129 bytes (without its sentinel), then
  the first 40 cells of row CRTCNT (the row clamped to 1..24 for the read),
  LINL40, LINL32, FORCLR, BAKCLR, BDRCLR, TXTNAM .. T32PAT (20 B) read back after the call,
  sum16 of FNKSTR (160 B), sum16 of all 16 KB of VRAM,
  the colour table's 32 bytes at RG3SAV x $40, and the sentinel $C3.
"""
import os
import re
import sys
from types import SimpleNamespace as NS

HERE = os.path.dirname(os.path.abspath(__file__))
ASM = os.path.join(HERE, "xinit4.asm")
INITXT, INIT32 = 0x6C, 0x6F
REC = 231
SENT = 0xC3


def _cases():
    out = []

    def add(call, width, key=0, rgg=0xA5, crt=13, tbl=0, fg=15, bg=4, bd=7, fill=0x5A, lab=0, rg1=None):
        rg1 = rgg if rg1 is None else rg1
        name = "INITXT" if call == INITXT else "INIT32"
        out.append(NS(call=call, name=name, width=width, key=key, prior=0, fg=fg, bg=bg, bd=bd, tbl=tbl, vdp=0,
                      rgg=rgg, crt=crt, fill=fill, lab=lab, rg1=rg1,
                      what=f"{name} width {width} key {'on' if key else 'off'} copies ${rgg:02X} CRTCNT {crt}"
                           + (" tables3" if tbl == 2 else " tables2" if tbl == 1 else "")
                           + (f" fill {fill:02X}" if fill != 0x5A else "")
                           + {0: "", 1: " 7-char labels", 2: " 10-char labels"}[lab]
                           + (f" FORCLR {fg:02X}" if fg != 15 else "")
                           + (f" RG1SAV {rg1:02X}" if rg1 != rgg else "")))
    for call, w in ((INITXT, 40), (INIT32, 32)):
        for rgg in (0x01, 0x04, 0x20, 0x80, 0xFE, 0xFB, 0xDF, 0x7F):         # walking bits and their complements
            add(call, w, 0, rgg=rgg)
    for w in (0, 80, 255):
        add(INITXT, w, 1)
    for w in (0, 255):
        add(INIT32, w, 1)
    add(INIT32, 32, 0, tbl=1)
    add(INIT32, 32, 1, tbl=1)
    add(INITXT, 40, 1, fill=0xA3)
    add(INIT32, 32, 1, fill=0xA3)
    add(INITXT, 40, 1, lab=1)
    add(INIT32, 32, 1, lab=1)
    # run 2 (the confirming pass): bit 1 walked alone, and RG0SAV / RG1SAV with different values
    for call, w in ((INITXT, 40), (INIT32, 32)):
        for rgg in (0x02, 0xFD):
            add(call, w, 0, rgg=rgg)
        add(call, w, 0, rgg=0xFE, rg1=0x01)
        add(call, w, 0, rgg=0x01, rg1=0xFE)
    # run 3 (the second confirming pass): 10-character labels, so INITXT's cut to slot - 1 binds; FORCLR $CA (the sprite
    # colour with bits 6 / 7 set)
    add(INITXT, 40, 1, lab=2)
    add(INITXT, 33, 1, lab=2)
    add(INIT32, 32, 1, fg=0xCA)
    # run 4 (the sixth review): widths 5n + 4, where "slot - 1" and "width / 5 - 1" differ, with labels that bind
    add(INITXT, 39, 1, lab=2)
    add(INIT32, 24, 1)
    add(INIT32, 19, 1)
    return out


CASES = _cases()


def caplen():
    return 4 + REC * len(CASES)


def table_asm():
    L = ["; ---- GENERATED by xinit4_cases.py --gen: call, width, key, prior, fg, bg, bd, tbl, vdp, rgg, crt, fill, lab; "
         "rg1; $FF ends ----",
         "cases:"]
    for c in CASES:
        L.append(f"                db      ${c.call:02X}, {c.width}, {c.key}, {c.prior}, {c.fg}, {c.bg}, {c.bd}, {c.tbl}, "
                 f"{c.vdp}, ${c.rgg:02X}, {c.crt}, ${c.fill:02X}, {c.lab}, ${c.rg1:02X}   ; {c.what}")
    L.append("                db      $FF")
    return "\n".join(L) + "\n"


def gen():
    s = open(ASM).read()
    s = s[:s.index("; ---- GENERATED by xinit4_cases.py")] + table_asm()
    s = re.sub(r"; @caplen [0-9A-F]+", f"; @caplen {caplen():04X}", s)
    s = re.sub(r"CAPLEN  equ     \d+", f"CAPLEN  equ     {caplen()}", s)
    open(ASM, "w").write(s)
    print(f"{len(CASES)} cases, capture {caplen()} B")


def decode(block):
    """REFUSES an incomplete block or a record without its sentinel (docs/spec-method.md §3a)."""
    if block[1] != 0xA5:
        sys.exit("FAIL: the XINIT4 block is not complete")
    if len(block) < caplen():
        sys.exit(f"FAIL: the XINIT4 block is {len(block)} B, {caplen()} expected -- the last record has no sentinel")
    out = []
    for i, c in enumerate(CASES):
        b = list(block[4 + REC * i: 4 + REC * (i + 1)])
        if b[REC - 1] != SENT:
            sys.exit(f"FAIL: XINIT4 record {i} has no sentinel")
        w16 = lambda j: b[j] | (b[j + 1] << 8)                      # noqa: E731
        t = b[174:194]
        out.append(NS(**vars(c), idx=i, rg=b[0:8], scrmod=b[8], oldscr=b[9], linlen=b[10], crtcnt=b[11],
                      csrx=b[12], csry=b[13], cnsdfg=b[14], lt=b[15:39], namesum=w16(39), patsum=w16(41),
                      colsum=w16(43), tailsum=w16(45), atrsum=w16(47), lastrow=b[49:89], row13=b[89:129],
                      rowc=b[129:169], linl40=b[169], linl32=b[170], colours=b[171:174],
                      tables=[t[j] | (t[j + 1] << 8) for j in range(0, 20, 2)], fnksum=w16(194), vsum=w16(196),
                      col=b[198:230]))
    return out


if __name__ == "__main__":
    if "--gen" in sys.argv:
        gen()
    else:
        print(f"{len(CASES)} cases, capture {caplen()} B")
