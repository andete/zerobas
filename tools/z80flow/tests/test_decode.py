def dec(hexs, addr=BASE):
    b = bytes.fromhex(hexs)
    return decode(lambda a: b[a - addr] if 0 <= a - addr < len(b) else None, addr)


class TestTable(unittest.TestCase):
    def test_table(self):
        for hexs, mn, ln, kind, cond, tgt in TABLE:
            with self.subTest(hexs=hexs):
                i = dec(hexs)
                self.assertEqual(i.mnem, mn)
                self.assertEqual(i.length, ln)
                self.assertEqual(i.kind, kind)
                self.assertEqual(i.cond, cond)
                self.assertEqual(i.target, tgt)
                self.assertIsNone(i.invalid, i.invalid)

    def test_all_lengths_consistent(self):
        """Every 1..4-byte prefix space decodes to a length 1..4 without exceptions."""
        for a in range(256):
            for b in range(256):
                for pre in ([], [0xDD], [0xED], [0xCB], [0xDD, 0xCB]):
                    seq = bytes(pre + [a, b, 0x12, 0x34])
                    i = decode(lambda x: seq[x] if x < len(seq) else None, 0)
                    self.assertTrue(1 <= i.length <= 4, (seq.hex(), i.length))
            if a > 3:
                break

    def test_effects(self):
        i = dec("8E")  # adc a,(hl)
        self.assertEqual(i.reads, m("A", "H", "L") | FC)
        self.assertEqual(i.writes, m("A") | ALLF)
        self.assertTrue(i.mem_r)
        i = dec("04")  # inc b: C untouched
        self.assertEqual(i.writes, m("B") | FS | FZ | FH | FPV | FN)
        i = dec("29")  # add hl,hl
        self.assertEqual(i.writes, m("H", "L") | FH | FN | FC)
        i = dec("78")  # ld a,b is a copy, not a read+write
        self.assertEqual(i.copies, [(U["A"], U["B"])])
        self.assertEqual(i.reads | i.writes, 0)
        i = dec("DD7E05")
        self.assertEqual(i.reads, m("IXH", "IXL"))
        self.assertEqual(i.writes, m("A"))
        i = dec("C0")  # ret nz reads Z
        self.assertEqual(i.reads, FZ | SP)
        i = dec("E2")  # jp po reads PV
        self.assertEqual(i.reads, FPV)
        i = dec("CB16")  # rl (hl) reads C
        self.assertTrue(i.reads & FC)
        i = dec("C5")
        self.assertEqual(i.stack, ("push", "BC"))
        i = dec("DDE3")
        self.assertEqual(i.stack, ("exsp", "IX"))
        i = dec("33")
        self.assertEqual(i.stack, ("adjsp", -1))
        i = dec("EDB0")
        self.assertEqual(i.writes, m("B", "C", "D", "E", "H", "L") | FH | FPV | FN)
        i = dec("37")  # scf
        self.assertEqual(i.writes, FH | FN | FC)
        self.assertEqual(i.reads, 0)

    def test_invalid(self):
        self.assertEqual(dec("ED00").invalid, "undefined ED opcode")
        self.assertEqual(dec("DD00").invalid, "useless DD/FD prefix")
        self.assertEqual(dec("DDDD21").invalid, "prefix followed by prefix")
        self.assertEqual(dec("C3").invalid, "runs off image")
        self.assertEqual(dec("DDEB").invalid, "useless DD/FD prefix")  # ex de,hl ignores DD


