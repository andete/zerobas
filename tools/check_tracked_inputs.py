"""check_tracked_inputs -- every file the BUILD reads is tracked by git.

WHY THIS EXISTS (D-UNTRACKED, 2026-10-17). D-BIOSINT (cdaff14a) added
cbios-repack/bios-keyscan.patch to tools/build_repacked_cbios.py's PATCHES and pinned
the sha1 it produces -- but never committed the file. Every local build and every gate
battery was green, because every one of them builds the WORKING TREE, where the file
existed; CI, which builds a fresh checkout, was red for eight commits (macOS: `can't
open patch`). Nothing in the battery compared the tree with what a clone gets.

What it checks, against `git ls-files`:
  1. every patch in tools/build_repacked_cbios.py's PATCHES is tracked;
  2. every `include "X"` in a TRACKED .asm / .inc under basic/ sub/ sub2/ disk/ tape/
     names a tracked file (X resolved from the repo root, as pasmo is run, beside the
     including file, or under sub/ -- the Makefile assembles both sub ROMs with
     `pasmo -I sub`). An include of build/ or derived/ output is skipped:
     those are generated by the build itself.
A missing include is reported too -- pasmo would refuse it anyway, but the message here
names the including line.

    python3 tools/check_tracked_inputs.py [--selftest]
Exit 0 clean; 1 an untracked or missing input.
"""
from __future__ import annotations

import os
import re
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIRS = ("basic", "sub", "sub2", "disk", "tape")
INCLUDE = re.compile(r'^\s*include\s+"([^"]+)"', re.IGNORECASE)
GENERATED = ("build/", "derived/")


def tracked_files() -> set[str]:
    out = subprocess.run(["git", "-C", REPO, "ls-files"], capture_output=True, text=True,
                         check=True).stdout
    return set(out.split("\n")) - {""}


def patches() -> list[str]:
    sys.path.insert(0, os.path.join(REPO, "tools"))
    import build_repacked_cbios as b          # noqa: E402  (its module scope has no side effects)
    return [os.path.relpath(p, REPO) for p in b.PATCHES]


def includes(tracked: set[str], read=None) -> list[tuple[str, int, str]]:
    """(including file, line number, included path as written) for every include line
    in a tracked source file. `read` is injectable for the selftest."""
    read = read or (lambda p: open(os.path.join(REPO, p), encoding="latin-1").read())
    out = []
    for f in sorted(tracked):
        if not f.startswith(tuple(d + "/" for d in DIRS)) or not f.endswith((".asm", ".inc")):
            continue
        for n, line in enumerate(read(f).split("\n"), 1):
            m = INCLUDE.match(line.split(";", 1)[0])
            if m:
                out.append((f, n, m.group(1)))
    return out


INCDIRS = ("sub",)                            # the Makefile's `pasmo -I sub` (sub.rom, sub2.rom)


def resolve(inc: str, src: str, exists) -> str | None:
    for cand in (os.path.normpath(inc), os.path.normpath(os.path.join(os.path.dirname(src), inc)),
                 *(os.path.normpath(os.path.join(d, inc)) for d in INCDIRS)):
        if exists(cand):
            return cand
    return None


def check(tracked: set[str], pats: list[str], incs, exists) -> list[str]:
    bad = []
    for p in pats:
        if p not in tracked:
            bad.append(f"PATCHES names {p}, which git does not track"
                       + ("" if exists(p) else " (and it does not exist)"))
    for src, n, inc in incs:
        if inc.startswith(GENERATED):
            continue
        hit = resolve(inc, src, exists)
        if hit is None:
            bad.append(f"{src}:{n}: include \"{inc}\" -- no such file")
        elif hit not in tracked:
            bad.append(f"{src}:{n}: include \"{inc}\" -> {hit}, which git does not track")
    return bad


def selftest() -> int:
    files = {"basic/main.asm": 'include "basic/a.inc"\n; include "basic/gone.inc"\n',
             "basic/a.inc": "nop\n", "basic/b.inc": 'include "c.inc"\n', "basic/c.inc": "nop\n"}
    exists = lambda p: p in files                              # noqa: E731
    read = lambda p: files[p]                                  # noqa: E731
    ok = True
    good = set(files)
    r = check(good, [], includes(good, read), exists)
    ok &= r == []                                              # all tracked, the comment ignored
    print(f"  SELFTEST {'PASS' if r == [] else 'FAIL'}  all tracked (a commented include ignored): {r}")
    less = good - {"basic/c.inc"}
    r = check(less, [], includes(less, read), exists)
    hit = len(r) == 1 and "basic/c.inc" in r[0]
    ok &= hit
    print(f"  SELFTEST {'PASS' if hit else 'FAIL'}  NEGATIVE: an untracked include beside its includer is RED: {r}")
    r = check(good, ["cbios-repack/x.patch"], includes(good, read), exists)
    hit = len(r) == 1 and "x.patch" in r[0]
    ok &= hit
    print(f"  SELFTEST {'PASS' if hit else 'FAIL'}  NEGATIVE: an untracked PATCHES entry is RED: {r}")
    return 0 if ok else 1


def main() -> int:
    if "--selftest" in sys.argv:
        return selftest()
    tracked = tracked_files()
    exists = lambda p: os.path.isfile(os.path.join(REPO, p))   # noqa: E731
    pats = patches()
    incs = includes(tracked)
    bad = check(tracked, pats, incs, exists)
    for b in bad:
        print(f"🔴 {b}")
    print(f"tracked-inputs: {len(pats)} patches, {len(incs)} include lines in tracked sources -- "
          f"{'OK, all tracked' if not bad else f'{len(bad)} UNTRACKED or missing'}")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
