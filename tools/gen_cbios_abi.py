"""gen_cbios_abi -- the C-BIOS addresses zerobas's BASIC calls, from the repacked C-BIOS's own symbol table.

D-CBIOSSYM (2026-11-22, for D-CBIOS032's rebase): BASIC calls a few C-BIOS bodies directly (its own wrappers fall
through to them), and these addresses were hand-written `equ`s pinned by tools/build_mainrom.py's old vector bytes.
tools/build_repacked_cbios.py now keeps the repacked build's symbol table (build/cbios_main_msx1_eu-repacked.sym),
so the addresses are GENERATED from C-BIOS's labels into basic/cbios-abi.inc -- a C-BIOS that moves its code moves
them too, and a renamed label fails here, loudly.

    python3 tools/gen_cbios_abi.py            # write basic/cbios-abi.inc
    python3 tools/gen_cbios_abi.py --check    # exit 1 if the committed file differs from a fresh one
    python3 tools/gen_cbios_abi.py --sym F    # read another build's symbol table

tools/build_patches.py runs it right after the repacked C-BIOS is built and before BASIC is assembled, so a
C-BIOS whose code moved can never be merged with the old addresses (2026-11-22: retiring grphed-cls.patch moved
`cls` by 4 B, and a hand-run build used the stale $0614 -- CLS's spec page failed 8 rules).
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SYM = os.path.join(ROOT, "build", "cbios_main_msx1_eu-repacked.sym")
OUT = os.path.join(ROOT, "basic", "cbios-abi.inc")

# the zerobas name -> (the C-BIOS label, what BASIC uses it for)
ABI = [
    ("CBIOS_BREAKX", "breakx", "C-BIOS's BREAKX body (basic/biosfnk.asm bios_breakx calls it)"),
    ("CBIOS_CLS", "cls", "C-BIOS's CLS body, past cls_z's `ret nz` (basic/main.asm bios_cls)"),
    ("CBIOS_GICINI", "gicini", "C-BIOS's GICINI body, the PSG only (basic/main.asm bios_gicini)"),
    ("CBIOS_TUPC", "tupc", "C-BIOS's TUPC body (basic/biosfnk.asm bios_tupc, every case but the edge)"),
    ("CBIOS_TDOWNC", "tdownc", "C-BIOS's TDOWNC body (basic/biosfnk.asm bios_tdownc, every case but the edge)"),
    ("CBIOS_NSETCX", "nsetcx", "C-BIOS's NSETCX body (basic/biosfnk.asm bios_nsetcx)"),
    ("CBIOS_CHPUT", "chput", "C-BIOS's CHPUT: the TTYPOS store at +27 is patched (basic/islands.asm)"),
]


def load(path=SYM):
    if not os.path.exists(path):
        sys.exit(f"gen_cbios_abi: {os.path.relpath(path, ROOT)} is missing -- `make repack-machine` writes it")
    out = {}
    for line in open(path):
        m = re.match(r"(\S+)\s+EQU\s+0?([0-9A-Fa-f]+)H", line)
        if m:
            out[m.group(1)] = int(m.group(2), 16)
    return out


def render(sym):
    lines = ["; Copyright (c) 2026 Joost Yervante Damad",
             "; SPDX-License-Identifier: BSD-2-Clause",
             ";",
             "; CLEAN-ROOM: addresses only, read from C-BIOS's own symbol table (C-BIOS: a peer clean-room",
             "; implementation whose source zerobas patches, docs/allowed-sources.md grade B); no reference-ROM",
             "; byte and no disassembly.",
             ";",
             "; GENERATED by tools/gen_cbios_abi.py from build/cbios_main_msx1_eu-repacked.sym -- do not edit;",
             "; `python3 tools/gen_cbios_abi.py` rewrites it, `make cbios-abi-check` checks it.",
             "; The C-BIOS bodies zerobas's BASIC calls directly, by C-BIOS's own labels (D-CBIOSSYM)."]
    missing = [lbl for _, lbl, _ in ABI if lbl not in sym]
    if missing:
        sys.exit(f"gen_cbios_abi: C-BIOS has no label {missing} -- renamed upstream? update ABI here")
    for name, lbl, why in ABI:
        lines.append(f"{name:<16}equ     ${sym[lbl]:04X}   ; {lbl}: {why}")
    return "\n".join(lines) + "\n"


def main(argv):
    sym = argv[argv.index("--sym") + 1] if "--sym" in argv else SYM
    text = render(load(sym))
    if "--check" in argv:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        if cur != text:
            print(f"cbios-abi-check: basic/cbios-abi.inc is STALE against build/cbios_main_msx1_eu-repacked.sym -- "
                  f"run `python3 tools/gen_cbios_abi.py` and rebuild")
            return 1
        print(f"OK: basic/cbios-abi.inc matches the repacked C-BIOS's labels ({len(ABI)} addresses)")
        return 0
    # only on a change: a rewrite with the same bytes bumps the mtime, and every ROM that includes the file
    # (sub.rom too) then reads as stale to the probe preflight -- 136 knife cuts refused on 2026-11-22
    if os.path.exists(OUT) and open(OUT).read() == text:
        print(f"unchanged: {os.path.relpath(OUT, ROOT)} ({len(ABI)} addresses)")
        return 0
    open(OUT, "w").write(text)
    print(f"wrote {os.path.relpath(OUT, ROOT)} ({len(ABI)} addresses)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
