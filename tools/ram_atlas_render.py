"""D-RAMATLAS: render docs/ram-atlas.md from scratchpad/ramatlas.json (tools/ram_atlas.py --run) and zerobas's own
RAM map (tools/ram_map.py). See tools/ram_atlas.py for how the JSON is measured."""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import ram_atlas as A  # noqa: E402
import ram_map  # noqa: E402

# the ROM slots per machine (page@slot -> kind); anything else is code running from RAM
ROMS = {
    "VG": {"0": "M", "0-0": "M"},
    "VGHBD": {"0": "M", "0-0": "M", "1": "D", "1-0": "D"},
    "CF": {"0": "M", "0-0": "M", "3-1": "D"},
    "ZBND": {"0": "M", "0-0": "M", "3-2": "S"},
    "ZBD": {"0": "M", "0-0": "M", "3-1": "D", "3-2": "S"},
}
LETTER = {"boot": "b", "INIT": "I", "H.RUNC": "H", "MSX-DOS": "D", "BASIC": "B"}
KINDS = "MDSR"


PAGES = {"M": ("0", "1"), "D": ("1",), "S": ("0", "1")}     # the pages each ROM occupies (MSX1: 32 KB main, 16 KB disk)


def kind(tag, writer):
    pg, slot = writer.split("@")
    k = ROMS[tag].get(slot)
    return k if k and pg in PAGES[k] else "R"


def cell(tag, entries):
    """'b:M I:D H:DR' -- per moment (in order), the writer kinds; '' when nothing writes the address."""
    per = {}
    for e in entries:
        m, w = e.split(":", 1)
        k = kind(tag, w)
        if m == "boot" and k == "M":
            continue       # the main ROM's power-on RAM test / clear: stated once in the header, not per row
        per.setdefault(m, set()).add(k)
    return " ".join(f"{LETTER[m]}:{''.join(k for k in KINDS if k in per[m])}" for m in A.MOMENTS if m in per)


def boot_m(tag, run):
    return sum(1 for es in run.values() if any(e.startswith("boot:") and kind(tag, e[5:]) == "M" for e in es))


def names(maps, a, b):
    out = []
    for comp in ("basic", "disk"):
        m = maps[comp]
        for x in range(a, b + 1):
            if x in m.byaddr:
                n = "/".join(m.byaddr[x])
                if n not in out:
                    out.append(n)
        if not any(x in m.byaddr for x in range(a, b + 1)):
            own = m.covering(a, a + 1)
            if own is not None:
                n = "(in " + "/".join(m.byaddr[own]) + ")"
                if n not in out:
                    out.append(n)
    s = ", ".join(out)
    return s if len(s) <= 90 else s[:87] + "..."


def render(json_path, doc_path):
    data = A.load() if json_path == A.JSON else {k: A.unpack(v) for k, v in json.load(open(json_path)).items()}
    cols = [(tag, scen) for tag, _, _, _ in A.MACHINES for scen in A.scenarios_for(tag) if f"{tag}/{scen}" in data]
    missing = [f"{t}/{s}" for t, _, _, _ in A.MACHINES for s in A.scenarios_for(t) if f"{t}/{s}" not in data]
    if missing:
        raise SystemExit(f"ram_atlas: no run for {', '.join(missing)} -- refusing to render a partial atlas")
    maps = {c: ram_map.Map(c, A.LO, A.HI) for c in ("basic", "disk")}
    sig = {}
    for a in range(A.LO, A.HI + 1):
        sig[a] = tuple(cell(t, data[f"{t}/{s}"].get(a, [])) for t, s in cols)
    rows, start = [], A.LO
    for a in range(A.LO + 1, A.HI + 2):
        if a > A.HI or sig[a] != sig[start]:
            rows.append((start, a - 1, sig[start]))
            start = a
    head = ["<!--", "Copyright (c) 2026 Joost Yervante Damad", "SPDX-License-Identifier: BSD-2-Clause", "-->",
            "<!-- GENERATED by tools/ram_atlas_render.py from scratchpad/ramatlas.json (tools/ram_atlas.py --run) "
            "and tools/ram_map.py. Do not edit by hand. -->", "",
            f"# High RAM atlas — ${A.LO:04X}-${A.HI:04X}, who writes what, when, on which machine", "",
            "> Generated (D-RAMATLAS). Every row is a run of addresses with the same writers at the same moments on "
            "every machine below. **Moments:** b boot, I INIT (a cartridge's HIMEM claim), H H.RUNC (after the "
            "cartridge scan), D MSX-DOS running, B (Disk) BASIC running. **Writers:** M main ROM, D disk ROM, S "
            "zerobas's sub ROM, R code running from RAM (MSX-DOS, a BASIC program's machine code, RAM-resident "
            "routines). An empty cell: nothing wrote the range in that run. **zerobas** names the cells zerobas "
            "declares there (basic/, disk/; `(in X)`: inside a declared buffer).", "",
            "> **Clean room:** the runs record the address written, the moment and the writing code's page@slot -- "
            "no value and no program counter, on any machine. So this page says WHO uses RAM, never WHAT a "
            "reference keeps in it; a class that needs values (what a published cell holds) comes from the "
            "published-cell probes.", "",
            "> **Scenarios:** " + "; ".join(f"`{s}`: {os.path.basename(d) if d else 'no disk'}, {sec} s, keys "
                                           + ", ".join(f"{t} s {k.replace(chr(92) + 'r', '⏎')[:24]!r}"
                                                       for t, k in keys)
                                           for s, (d, sec, keys, _) in A.SCENARIOS.items()), "",
            "> **Power-on:** the main ROM's writes before any cartridge's INIT are left out of the rows (they are "
            "the RAM test and clear, not a use of the RAM). Addresses of the range the main ROM writes at boot, per "
            "run: " + ", ".join(f"{t} {s} {boot_m(t, data[f'{t}/{s}'])}" for t, s in cols) + ".", "",
            f"{len(rows)} rows.", ""]
    hdr = "| range | B | " + " | ".join(f"{t} {s}" for t, s in cols) + " | zerobas |"
    sep = "|---|---:|" + "---|" * len(cols) + "---|"
    lines = head + [hdr, sep]
    for a, b, s in rows:
        lines.append(f"| `${a:04X}-${b:04X}` | {b - a + 1} | " + " | ".join(x or " " for x in s)
                     + f" | {names(maps, a, b)} |")
    text = "\n".join(lines) + "\n"
    with open(doc_path, "w") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(doc_path, ROOT)}: {len(rows)} rows over {len(cols)} runs")
    return 0


if __name__ == "__main__":
    sys.exit(render(A.JSON, A.DOC))
